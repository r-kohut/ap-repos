#include <cmath>
#include "dod.h"
#include "sum.h"
#include "var.h"

using namespace nsDod;
using namespace nsVar;

void nsSum::sum()
{
    n = 0;          // кількість доданків, використаних після першого
    a = 1;          // перший доданок
    s = a;          // сума починається з першого доданку
    do
    {
        n++;
        dod();      // обчислення наступного доданку
        s += a;
    } while (fabs(a) > e);
}